CREATE TABLE inbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(80) NOT NULL,
    event_type VARCHAR(120) NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    payload JSONB NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_inbox_events_source_external UNIQUE (source, external_id)
);
CREATE INDEX ix_inbox_events_received_at ON inbox_events (received_at);

CREATE TABLE processing_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_event_id BIGINT NOT NULL REFERENCES inbox_events(id),
    status VARCHAR(32) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_processing_jobs_inbox_event UNIQUE (inbox_event_id)
);
CREATE INDEX ix_processing_jobs_status_available ON processing_jobs (status, available_at);

CREATE TABLE outbox_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_key VARCHAR(255) NOT NULL,
    action_type VARCHAR(120) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_outbox_actions_action_key UNIQUE (action_key)
);
CREATE INDEX ix_outbox_actions_status_available ON outbox_actions (status, available_at);

CREATE TABLE chat_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_jid VARCHAR(255) NOT NULL,
    archived BOOLEAN NULL,
    snapshot_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_chat_snapshot_chat_jid UNIQUE (chat_jid)
);

CREATE TABLE identity_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias VARCHAR(255) NOT NULL,
    canonical_identity VARCHAR(255) NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_identity_aliases_alias UNIQUE (alias)
);
CREATE INDEX ix_identity_aliases_canonical ON identity_aliases (canonical_identity);

CREATE TABLE pending_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_jid VARCHAR(255) NOT NULL,
    payload JSONB NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pending_notification_chat_jid UNIQUE (chat_jid)
);
CREATE INDEX ix_pending_notification_due ON pending_notification (due_at);

CREATE TABLE processed_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id VARCHAR(255) NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_processed_message_message_id UNIQUE (message_id)
);
