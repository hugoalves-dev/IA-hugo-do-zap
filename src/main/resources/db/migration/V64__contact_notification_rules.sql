-- Rules are opt-in. No JC/CH defaults are installed by this migration.
CREATE TABLE contact_notification_rules (
    selector_type VARCHAR(16) NOT NULL CHECK (selector_type IN ('MARKER','CONTACT')),
    selector VARCHAR(255) NOT NULL CHECK (length(trim(selector)) BETWEEN 2 AND 255),
    profile_name VARCHAR(80) NULL REFERENCES policy_profiles(profile_name),
    priority VARCHAR(12) NOT NULL CHECK (priority IN ('NORMAL','PRIORITY')),
    updated_by BIGINT NOT NULL CHECK (updated_by > 0),
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (selector_type,selector)
);

CREATE TABLE contact_notification_rule_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    selector_type VARCHAR(16) NOT NULL,
    selector VARCHAR(255) NOT NULL,
    action VARCHAR(8) NOT NULL CHECK (action IN ('UPSERT','REMOVE')),
    previous_profile VARCHAR(80),
    previous_priority VARCHAR(12),
    next_profile VARCHAR(80),
    next_priority VARCHAR(12),
    actor_user_id BIGINT NOT NULL CHECK (actor_user_id > 0),
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_contact_notification_rule_audit_changed_at ON contact_notification_rule_audit(changed_at);
