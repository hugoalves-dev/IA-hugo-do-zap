CREATE TABLE classification_prompt_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 16000),
    content_hash varchar(64) NOT NULL CHECK (
        content_hash ~ '^[0-9a-f]{64}$' AND content_hash = encode(sha256(convert_to(body, 'UTF8')), 'hex')),
    origin varchar(16) NOT NULL CHECK (origin IN ('manual', 'ai_assisted')),
    description varchar(500) NOT NULL DEFAULT '',
    author_id bigint NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE FUNCTION reject_classification_prompt_revision_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'classification prompt revisions are immutable' USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER classification_prompt_revision_immutable
    BEFORE UPDATE OR DELETE ON classification_prompt_revisions
    FOR EACH ROW EXECUTE FUNCTION reject_classification_prompt_revision_mutation();

CREATE TABLE classification_prompt_drafts (
    id uuid PRIMARY KEY,
    owner_id bigint NOT NULL,
    base_revision bigint REFERENCES classification_prompt_revisions(id),
    body text NOT NULL CHECK (char_length(body) <= 16000),
    origin varchar(16) NOT NULL CHECK (origin IN ('manual', 'ai_assisted')),
    description varchar(500) NOT NULL DEFAULT '',
    status varchar(16) NOT NULL CHECK (status IN ('editing', 'preview', 'cancelled', 'activated')),
    refinement_count integer NOT NULL DEFAULT 0 CHECK (refinement_count BETWEEN 0 AND 3),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    expires_at timestamptz NOT NULL
);
CREATE INDEX classification_prompt_drafts_owner ON classification_prompt_drafts(owner_id, expires_at);

CREATE TABLE classification_prompt_active (
    singleton_id integer PRIMARY KEY CHECK (singleton_id = 1),
    revision_id bigint REFERENCES classification_prompt_revisions(id)
);
INSERT INTO classification_prompt_active(singleton_id, revision_id) VALUES (1, NULL);

CREATE TABLE classification_prompt_transitions (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    previous_revision bigint REFERENCES classification_prompt_revisions(id),
    next_revision bigint REFERENCES classification_prompt_revisions(id),
    event varchar(16) NOT NULL CHECK (event IN ('activate', 'restore', 'reset')),
    author_id bigint NOT NULL,
    changed_at timestamptz NOT NULL,
    CHECK ((event = 'reset' AND next_revision IS NULL)
        OR (event IN ('activate', 'restore') AND next_revision IS NOT NULL))
);
