ALTER TABLE chat_snapshot
    ADD COLUMN display_name TEXT NULL,
    ADD COLUMN is_group BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN synchronized_snapshot BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE pending_notification
    ADD COLUMN expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + INTERVAL '7 days');

CREATE TABLE quarantined_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_kind VARCHAR(40) NOT NULL,
    source_event_id VARCHAR(255) NULL,
    reason VARCHAR(80) NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sensitive_expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_quarantined_events_max_retention
        CHECK (sensitive_expires_at <= received_at + INTERVAL '7 days')
);
CREATE INDEX ix_quarantined_events_expiry ON quarantined_events (sensitive_expires_at);

CREATE INDEX ix_pending_notification_expiry ON pending_notification (expires_at);
